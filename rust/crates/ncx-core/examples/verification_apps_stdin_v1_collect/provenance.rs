pub(super) fn build_info() -> Result<Value, String> {
    let executable = std::env::current_exe().map_err(|_| "executable_path")?;
    let mut result = json!({"executable_sha256":sha(&std::fs::read(executable).map_err(|_|"executable_read")?),
        "policy_version":verification::types::POLICY_VERSION,"runner_schema":"stdin-development-only-v1"});
    for (role, _, bytes) in sources() {
        result[role] = json!(sha(bytes));
    }
    Ok(result)
}

pub(super) fn check_current(cohort: &Value) -> Result<(), String> {
    let directory =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("examples/verification_apps_stdin_v1_collect");
    for (_, relative, bytes) in sources() {
        let path = directory
            .join(relative)
            .canonicalize()
            .map_err(|_| "compiled_path_missing")?;
        let expected = sha(bytes);
        if sha(&std::fs::read(&path).map_err(|_| "compiled_source_read")?) != expected {
            return Err("compiled_source_changed".into());
        }
        if !cohort["bindings"]
            .as_array()
            .ok_or("bindings")?
            .iter()
            .any(|bound| {
                Path::new(bound["file"].as_str().unwrap_or(""))
                    .canonicalize()
                    .ok()
                    .as_ref()
                    == Some(&path)
                    && bound["sha256"] == expected
            })
        {
            return Err("compiled_owner_missing_from_cohort".into());
        }
    }
    Ok(())
}
